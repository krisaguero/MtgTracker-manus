import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const researchDirectory = resolve(root, "data/market/research");
const outputFile = resolve(root, "client/src/data/marketWatchBacklog.json");
const generatedAt = new Date().toISOString();

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

function dateFromFile(file) {
  return basename(file, ".json");
}

function cardKey(card) {
  return `${card.setCode || ""}:${card.collectorNumber || card.name}`.toLowerCase();
}

function selectDailyCards(post) {
  const cards = Array.isArray(post.cards) ? post.cards : [];
  const nonZero = cards.filter(card => Number(card.percentChange) !== 0);
  const source = nonZero.length ? nonZero : cards;
  return source.slice(0, 3).map(card => ({
    ...card,
    briefStatus: nonZero.length ? "mover" : "flat-baseline",
  }));
}

function isoWeek(dateKey) {
  const date = new Date(`${dateKey}T12:00:00Z`);
  const day = date.getUTCDay() || 7;
  date.setUTCDate(date.getUTCDate() + 4 - day);
  const yearStart = new Date(Date.UTC(date.getUTCFullYear(), 0, 1));
  return `${date.getUTCFullYear()}-W${String(Math.ceil(((date - yearStart) / 86400000 + 1) / 7)).padStart(2, "0")}`;
}

function buildWeekly(posts, week) {
  const byCard = new Map();
  for (const post of posts.filter(entry => isoWeek(entry.dateKey) === week)) {
    for (const card of post.cards || []) {
      const key = cardKey(card);
      const current = byCard.get(key) || {
        ...card,
        appearances: 0,
        dates: [],
        maxAbsChange: 0,
        cumulativeChange: 0,
      };
      current.appearances += 1;
      current.dates.push(post.dateKey);
      current.maxAbsChange = Math.max(current.maxAbsChange, Math.abs(Number(card.percentChange) || 0));
      current.cumulativeChange += Number(card.percentChange) || 0;
      current.percentChange = Number(card.percentChange) || 0;
      current.currentUsd = card.currentUsd;
      current.verifiedAt = card.verifiedAt;
      byCard.set(key, current);
    }
  }
  return [...byCard.values()]
    .sort((a, b) => b.maxAbsChange - a.maxAbsChange || b.appearances - a.appearances)
    .slice(0, 10)
    .map((card, index) => ({ ...card, rank: index + 1 }));
}

async function main() {
  const files = (await import("node:fs/promises")).readdir(researchDirectory)
    .then(names => names.filter(name => /^\d{4}-\d{2}-\d{2}\.json$/.test(name)).sort())
    .then(names => names.map(name => resolve(researchDirectory, name)));
  const researchFiles = await files;
  const posts = [];
  for (const file of researchFiles) {
    const post = await readJson(file);
    const dateKey = post.dateKey || dateFromFile(file);
    posts.push({
      id: post.id || `${dateKey}-${post.slug || "market-watch"}`,
      dateKey,
      title: post.title,
      label: post.label,
      slug: post.slug,
      kind: post.kind,
      summary: post.summary,
      dataWindow: post.dataWindow,
      selectionMode: post.selectionMode,
      selectionNote: post.selectionNote,
      generatedAt: post.generatedAt,
      cards: selectDailyCards(post),
      fullCardCount: Array.isArray(post.cards) ? post.cards.length : 0,
      source: `data/market/research/${basename(file)}`,
    });
  }
  posts.sort((a, b) => b.dateKey.localeCompare(a.dateKey));
  const weekKeys = [...new Set(posts.map(post => isoWeek(post.dateKey)))];
  const weekly = weekKeys.map(week => ({
    week,
    label: `Week ${week.split("-W")[1]} · ${week.split("-W")[0]}`,
    posts: posts.filter(post => isoWeek(post.dateKey) === week).length,
    cards: buildWeekly(posts, week),
  }));
  const output = {
    schemaVersion: 1,
    generatedAt,
    source: "Archived data/market/research/*.json generated by the daily market workflow",
    dailyBriefCardLimit: 3,
    dailyPosts: posts,
    weekly,
  };
  await mkdir(dirname(outputFile), { recursive: true });
  await writeFile(outputFile, `${JSON.stringify(output, null, 2)}\n`, "utf8");
  console.log(`Market backlog complete: ${posts.length} daily posts, ${weekly.length} weekly digests.`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
